    def _bulk_flag(target_state: str) -> None:
        if state.current_scores.empty:
            _status("No score file is loaded for this ROI.")
            return
        if "ObjectNumber" not in state.current_scores.columns or "artifact_probability" not in state.current_scores.columns:
            _status("Score table must contain ObjectNumber and artifact_probability columns.")
            return

        scores = state.current_scores.copy()
        scores["artifact_probability"] = pd.to_numeric(scores["artifact_probability"], errors="coerce")
        scores["ObjectNumber"] = pd.to_numeric(scores["ObjectNumber"], errors="coerce")
        scores = scores.dropna(subset=["ObjectNumber", "artifact_probability"])

        if target_state == FLAGGED_GOOD:
            candidates = scores[scores["artifact_probability"] <= lower_threshold_spin.value()]
            candidates = candidates.sort_values("artifact_probability", ascending=True)
        else:
            candidates = scores[scores["artifact_probability"] >= upper_threshold_spin.value()]
            candidates = candidates.sort_values("artifact_probability", ascending=False)

        selected_ids = []
        for object_id in candidates["ObjectNumber"].astype(int).tolist():
            current_state = state.current_labels.state_for(object_id)
            if avoid_confirmed_checkbox.isChecked() and current_state in {CONFIRMED_GOOD, CONFIRMED_ARTIFACT}:
                continue
            if exclude_flagged_checkbox.isChecked() and current_state in {FLAGGED_GOOD, FLAGGED_ARTIFACT}:
                continue
            selected_ids.append(object_id)
            if max_bulk_spin.value() > 0 and len(selected_ids) >= max_bulk_spin.value():
                break

        _push_undo()
        changed = 0
        for object_id in selected_ids:
            if state.current_labels.set_state(object_id, target_state, source="threshold-assisted"):
                changed += 1
        _refresh_label_layers()
        _status(f"Flagged {changed} cell(s) as {target_state.replace('_', ' ')}.")

