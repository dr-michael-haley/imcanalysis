    def _train_model() -> None:
        _save_current_roi_state()
        _refresh_feature_selection()
        if state.feature_table is None or state.feature_dictionary is None:
            _status("Load feature table and dictionary before training.")
            return
        if not state.selected_features:
            _status("No selected features are available for training.")
            return

        confirmed = load_all_confirmed_labels(state.folders["labels"])
        result = train_classifier(
            state.feature_table,
            confirmed,
            state.selected_features,
            model_type=model_type_combo.currentText(),
            feature_table_path=state.feature_table_path,
            dictionary_path=state.feature_dictionary_path,
            selected_categories=state.selected_categories,
        )
        for warning in result.warnings:
            _status(f"WARNING: {warning}")
        for error in result.errors:
            _status(f"ERROR: {error}")
        if not result.ok:
            return

        state.model_bundle = result.bundle
        state.model_bundle.metadata["feature_dictionary_selection"] = state.feature_dictionary.to_metadata(
            state.selected_categories,
            state.selected_features,
        )
        state.model_bundle.metadata["label_file_fingerprints"] = _all_label_file_fingerprints()
        model_path_saved, metadata_path = save_model_bundle(state.model_bundle, state.folders["models"], make_latest=True)
        model_file_input.setText(str(model_path_saved))
        _set_model_status()
        _update_status_summary()
        _status(
            f"Trained model on {state.model_bundle.metadata['training_example_count']} examples "
            f"({state.model_bundle.metadata['confirmed_good_count']} good, "
            f"{state.model_bundle.metadata['confirmed_artifact_count']} artifact)."
        )
        _status(f"Saved model metadata: {metadata_path}")

