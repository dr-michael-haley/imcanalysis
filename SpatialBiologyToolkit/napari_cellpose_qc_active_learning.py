def main() -> None:
    parser = argparse.ArgumentParser(description="Napari active-learning QC for CellPose IMC masks.")
    parser.add_argument("--masks", default="masks", help="Folder containing one mask TIFF per ROI.")
    parser.add_argument("--images", default="images", help="Images folder. Use ';' to separate multiple folders.")
    parser.add_argument("--features", default=None, help="Precomputed feature table CSV/parquet.")
    parser.add_argument("--dictionary", default=None, help="Feature column dictionary CSV.")
    parser.add_argument("--output", default="qc_classifier", help="QC output folder.")
    parser.add_argument("--roi-column", default="ROI", help="ROI identifier column in the feature table.")
    parser.add_argument("--object-column", default="ObjectNumber", help="Mask label/object ID column in the feature table.")
    parser.add_argument("--initial-roi", default=None, help="ROI to load first.")
    parser.add_argument("--model", default=None, help="Saved classifier .joblib to load.")
    args = parser.parse_args()
    image_folders = [folder for folder in str(args.images).split(";") if folder]
    napari_cellpose_qc_active_learning(
        masks_folder=args.masks,
        image_folders=image_folders,
        feature_table_path=args.features,
        feature_dictionary_path=args.dictionary,
        output_folder=args.output,
        roi_column=args.roi_column,
        object_column=args.object_column,
        initial_roi=args.initial_roi,
        model_path=args.model,
    )


if __name__ == "__main__":
    main()
