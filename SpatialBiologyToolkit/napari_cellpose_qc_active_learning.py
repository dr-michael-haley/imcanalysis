"""
Napari active-learning QC tool for CellPose-SAM IMC segmentation masks.

What it does
------------
This viewer adds a safe object-level QC layer after CellPose-SAM segmentation.
It loads the precomputed per-cell feature table generated by
``SpatialBiologyToolkit/scripts/cellpose_sam.py``, lets a user stage good and
artifact mask labels, confirms staged labels into a reusable training set,
trains a lightweight tabular classifier, applies artifact-probability scores,
and exports cleaned masks without overwriting the original masks.

Expected inputs
---------------
* ``images``: by default an ``images`` folder. The preferred layout follows
  ``napari_imc_explorer``: ``images/<ROI>/<channel>.tiff``. A direct
  one-image-per-ROI layout such as ``images/<ROI>.tiff`` is also accepted.
* ``masks``: by default a ``masks`` folder with one TIFF mask per ROI, named
  ``<ROI>.tiff`` or ``<ROI>.tif``.
* Feature table: usually ``masks/CellposeSAM_cell_metrics.csv``.
* Feature dictionary: usually
  ``masks/CellposeSAM_cell_metrics_feature_dictionary.csv``.
* QC output folder: by default ``qc_classifier``.

Saved outputs
-------------
The tool writes resumable state under the QC output folder:

* ``labels/<ROI>_labels.csv``: confirmed and flagged object labels.
* ``scores/<ROI>_scores.csv``: artifact_probability scores.
* ``models/*.joblib`` and matching metadata JSON files.
* ``masks_cleaned/<ROI>_cleaned_mask.tiff``: exported cleaned masks.
* ``exports/<ROI>_cell_qc.csv``: per-cell audit tables.
* ``metadata/*.json`` and ``logs/qc_session_log.txt``.

Launch example
--------------
``python -m SpatialBiologyToolkit.napari_cellpose_qc_active_learning --masks masks --images images``

Score convention
----------------
``artifact_probability = 0`` means likely good cell.
``artifact_probability = 1`` means likely artifact.

Assumptions from repository inspection
--------------------------------------
The upstream CellPose-SAM metrics script uses ``ROI`` and ``ObjectNumber`` as
the canonical feature-row identifiers. Its feature dictionary is indexed by
``feature`` and includes ``type/source`` and ``description`` columns. This tool
uses the dictionary to select model inputs and excludes identifiers, metadata,
and segmentation-configuration columns unless a future dictionary explicitly
marks them as valid model inputs.
"""

