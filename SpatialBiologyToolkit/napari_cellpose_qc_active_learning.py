    def _annotate_object(object_id: int, *, source: str = "manual") -> None:
        mode = annotation_mode_group.checkedButton().text()
        if object_id <= 0:
            clicked_cell_label.setText("Clicked cell: background")
            return

        current_score = None
        if not state.current_scores.empty and "ObjectNumber" in state.current_scores.columns:
            score_rows = state.current_scores[pd.to_numeric(state.current_scores["ObjectNumber"], errors="coerce") == object_id]
            if not score_rows.empty:
                current_score = float(score_rows.iloc[0]["artifact_probability"])

        clicked_cell_label.setText(
            f"Clicked cell: ROI={state.current_roi}, ObjectNumber={object_id}, "
            f"score={'NA' if current_score is None else f'{current_score:.3f}'}, "
            f"state={state.current_labels.state_for(object_id) or 'none'}"
        )

        if mode == "inspect only":
            return

        _push_undo()
        changed = False
        if mode == "flag as good":
            changed = state.current_labels.set_state(object_id, FLAGGED_GOOD, source=source)
        elif mode == "flag as artifact":
            changed = state.current_labels.set_state(object_id, FLAGGED_ARTIFACT, source=source)
        elif mode == "erase flagged label":
            changed = state.current_labels.remove_flagged(object_id)
        elif mode == "remove any label":
            changed = state.current_labels.remove_any(object_id)

        if changed:
            _refresh_label_layers()

    def _viewer_click_callback(viewer_obj, event) -> None:
        if state.current_mask is None or event.type != "mouse_press" or event.button != 1:
            return
        position = event.position
        if len(position) < 2:
            return
        row = int(round(position[-2]))
        col = int(round(position[-1]))
        if row < 0 or col < 0 or row >= state.current_mask.shape[0] or col >= state.current_mask.shape[1]:
            return
        object_id = int(state.current_mask[row, col])
        _annotate_object(object_id)

